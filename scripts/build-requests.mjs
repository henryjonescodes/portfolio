// Writes .work/REQUESTS.md: everything the site owner still has to source, grouped by entry,
// with the draft brief, where it shows and the path to drop the file at. Every placeholder in
// src/data carries a request id; a file named by that id in src/assets/requests replaces it.
import { mkdirSync, writeFileSync } from 'node:fs';
import { loadSiteData } from './lib/load-site-data.mjs';

const OUT = '.work/REQUESTS.md';
const REQUEST_DIR = 'src/assets/requests';

const [{ experienceData }, { projectsData }, { sourcedRequests, draftRegistry }] = await loadSiteData([
  '/src/data/experience.ts',
  '/src/data/projects.ts',
  '/src/utils/requests.ts',
]);

const isPlaceholder = (v) =>
  v && typeof v === 'object' && typeof v.placeholder === 'string' && 'request' in v;

// Finds every placeholder under an entry and describes where it shows.
const collect = (node, where, found) => {
  if (Array.isArray(node)) {
    node.forEach((child, i) => collect(child, { ...where, index: i }, found));
    return;
  }
  if (!node || typeof node !== 'object' || typeof node === 'function') return;
  if (isPlaceholder(node)) {
    found.push({ ...node, where: where.label });
    return;
  }
  for (const [key, value] of Object.entries(node)) {
    if (key === 'media') {
      const label = where.inPanels
        ? where.effort
          ? `Effort "${where.effort}", media panel`
          : 'Entry media panel'
        : where.shape
          ? `Gallery card (${where.shape})`
          : 'Entry preview';
      collect(value, { ...where, label }, found);
    } else if (key === 'gallery') {
      value.forEach((card) => collect(card, { ...where, shape: card.shape }, found));
    } else if (key === 'efforts') {
      value.forEach((effort) => collect(effort, { ...where, effort: effort.id }, found));
    } else if (key === 'panels') {
      collect(value, { ...where, inPanels: true }, found);
    }
  }
};

const entries = [
  ...Object.values(experienceData).map((e) => ['Experience', e]),
  ...Object.values(projectsData).map((e) => ['Project', e]),
];

const cell = (text) => String(text).replace(/\|/g, '\\|');
const seen = new Set();
let total = 0;
let missing = 0;
const sections = [];

for (const [section, entry] of entries) {
  const found = [];
  collect(entry, {}, found);
  if (!found.length) continue;
  const rows = found.map((r) => {
    if (seen.has(r.request)) throw new Error(`Duplicate request id: ${r.request}`);
    seen.add(r.request);
    const sourced = r.request in sourcedRequests;
    total += 1;
    if (!sourced) missing += 1;
    return `| \`${r.request}\` | ${r.kind ?? 'image'} | ${cell(r.placeholder)} | ${cell(r.where)} | ${
      sourced ? 'sourced' : 'missing'
    } | \`${REQUEST_DIR}/${r.request}.{jpg,png,webp,mp4}\` |`;
  });
  sections.push(
    `## ${section}: ${entry.title ?? entry.id}\n\n| Id | Kind | Brief | Shows in | Status | Drop the file at |\n| --- | --- | --- | --- | --- | --- |\n${rows.join('\n')}`,
  );
}

// Drafted prose: ids are `<entry>-<field>` or `<entry>-<effort>-<field>`.
const FIELD_LABELS = { blurb: 'Entry blurb', summary: 'Effort summary' };
const truncate = (text, max = 160) => (text.length > max ? `${text.slice(0, max - 3)}...` : text);
const drafts = [...draftRegistry.values()].sort((a, b) => a.request.localeCompare(b.request));
const draftsOpen = drafts.filter((d) => !d.approved).length;
const proseRows = drafts.map((d) => {
  const field = d.request.slice(d.request.lastIndexOf('-') + 1);
  return `| \`${d.request}\` | ${cell(truncate(d.text.replace(/\s+/g, ' ')))} | ${
    FIELD_LABELS[field] ?? field
  } | ${d.approved ? 'approved' : 'draft'} | \`${REQUEST_DIR}/${d.request}.md\` |`;
});
const proseSection = drafts.length
  ? `## Prose to approve\n\n| Id | Current draft | Shows in | Status | Drop the text at |\n| --- | --- | --- | --- | --- |\n${proseRows.join('\n')}`
  : '';

const body = `# Content requests

Generated by \`npm run requests\`. Do not edit.

Media: ${total - missing} of ${total} sourced, ${missing} missing. Drop a file named by its id into \`${REQUEST_DIR}/\` and the mock is replaced with no code change. Images take jpg, png or webp; a video takes mp4.

Prose: ${drafts.length - draftsOpen} of ${drafts.length} approved, ${draftsOpen} still draft. Put the approved text in \`${REQUEST_DIR}/<id>.md\` and it replaces the draft.

${[...sections, proseSection].filter(Boolean).join('\n\n')}
`;

mkdirSync('.work', { recursive: true });
writeFileSync(OUT, body);
console.log(
  `requests: ${missing} media missing of ${total}, ${draftsOpen} drafts of ${drafts.length}, written to ${OUT}`,
);
